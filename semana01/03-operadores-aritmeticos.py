a = 10
b = 50

# Suma
resultado = a + b
print(resultado)

# Resta
resultado = a - b
print(resultado)

# Multiplicación
resultado = a * b
print(resultado)

# Divisón
resultado = a / b
print(resultado)

# División exacta (descarta decimales)
resultado = a // b
print(resultado)

# Modulo (Resto de la división)
resultado = a % b
print(resultado)

# Potencia
resultado = a ** b
print(resultado)

# Para los string
palabara1 = 'ala'
palabara2 = 'ole'
# Suma > Concatenación
resultado = palabara1 + palabara2
print(resultado)

# Multiplicación  (Si multiplico mi string por un entero se repetirá la cantidad de veces)
resultado = palabara1 * 2
print(resultado)